// The `fvtt.*` reference for run-script (issue #4): every page function the script facade exposes,
// with its argument shape one level deep and its return type, read from the TypeScript program
// itself (src/page/index.ts's `api` block), so the reference can never drift from the seam.
//
//   node scripts/measure/run-script-api.mjs            # writes docs/run-script-api.md
//   node scripts/measure/run-script-api.mjs --check    # exits 1 when the file is stale
//
// Grouped by the page module each function lives in. Offline; no Foundry.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const ENTRY = join(ROOT, 'src', 'page', 'index.ts');
const OUT = join(ROOT, 'docs', 'run-script-api.md');
const check = process.argv.includes('--check');

const cfgFile = ts.findConfigFile(ROOT, ts.sys.fileExists, 'tsconfig.json');
const cfg = ts.parseJsonConfigFileContent(
  ts.readConfigFile(cfgFile, ts.sys.readFile).config,
  ts.sys,
  ROOT
);
const program = ts.createProgram([ENTRY], cfg.options);
const checker = program.getTypeChecker();
const source = program.getSourceFile(ENTRY);
if (!source) throw new Error(`cannot load ${ENTRY}`);

/** The `const api = { … }` declaration. */
let apiDecl = null;
ts.forEachChild(source, node => {
  if (ts.isVariableStatement(node)) {
    for (const d of node.declarationList.declarations) {
      if (ts.isIdentifier(d.name) && d.name.text === 'api') apiDecl = d;
    }
  }
});
if (!apiDecl) throw new Error('no `const api = {…}` in src/page/index.ts');

const FLAGS =
  ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope;
const typeText = t => checker.typeToString(t, undefined, FLAGS);
const docOf = sym => {
  if (!sym) return '';
  const text = ts.displayPartsToString(sym.getDocumentationComment(checker)).trim();
  const firstPara = text.split(/\n\s*\n/)[0] ?? '';
  return firstPara.replace(/\s+/g, ' ').trim();
};
const unwrapPromise = t => {
  if (t.symbol?.name === 'Promise') {
    const args = checker.getTypeArguments(t);
    if (args.length) return args[0];
  }
  return t;
};

/** One level of an object type's properties: `name?: type — doc`. */
function fields(t) {
  if (!t || t.flags & ts.TypeFlags.Primitive || !t.getProperties) return [];
  if (checker.isArrayType?.(t)) return [];
  return t.getProperties().map(p => {
    const decl = p.valueDeclaration ?? p.declarations?.[0];
    const pt = decl
      ? checker.getTypeOfSymbolAtLocation(p, decl)
      : checker.getDeclaredTypeOfSymbol(p);
    const optional = !!(p.flags & ts.SymbolFlags.Optional);
    const nonNull = optional ? checker.getNonNullableType(pt) : pt;
    return { name: p.name, optional, type: typeText(nonNull), doc: docOf(p) };
  });
}

const groups = new Map();
const apiType = checker.getTypeAtLocation(apiDecl.name);
for (const member of apiType.getProperties()) {
  const name = member.name;
  if (name === 'runScript' || name === 'undoScript') continue;
  const memberDecl = member.valueDeclaration ?? member.declarations?.[0];
  const fnType = checker.getTypeOfSymbolAtLocation(member, memberDecl);
  const sig = fnType.getCallSignatures()[0];
  if (!sig) continue;
  // The documentation and the home file ride the function's own symbol, behind the import alias.
  let fnSym = ts.isShorthandPropertyAssignment(memberDecl)
    ? checker.getShorthandAssignmentValueSymbol(memberDecl)
    : checker.getSymbolAtLocation(memberDecl.name ?? memberDecl);
  if (fnSym && fnSym.flags & ts.SymbolFlags.Alias) fnSym = checker.getAliasedSymbol(fnSym);
  const home = fnSym?.declarations?.[0]?.getSourceFile().fileName ?? ENTRY;
  const group = relative(join(ROOT, 'src', 'page'), home)
    .replace(/\\/g, '/')
    .replace(/\.ts$/, '');
  const params = sig.getParameters().map(p => {
    const pt = checker.getTypeOfSymbolAtLocation(p, p.valueDeclaration ?? memberDecl);
    const optional =
      !!(p.flags & ts.SymbolFlags.Optional) || checker.isOptionalParameter?.(p.valueDeclaration);
    return {
      name: p.name,
      optional,
      type: typeText(pt),
      fields: fields(checker.getNonNullableType(pt)),
    };
  });
  const ret = unwrapPromise(sig.getReturnType());
  const entry = {
    name,
    doc: docOf(fnSym),
    params,
    returns: typeText(ret),
    returnFields: fields(ret),
  };
  if (!groups.has(group)) groups.set(group, []);
  groups.get(group).push(entry);
}

const lines = [];
lines.push('# run-script — the `fvtt.*` reference');
lines.push('');
lines.push(
  'Generated by `scripts/measure/run-script-api.mjs` from `src/page/index.ts`; never edited by hand. ' +
    'Every function here is what a tool calls in the page, offered to a `run-script` program as ' +
    '`await fvtt.<name>(args)`. Arguments are the tool’s own shapes, one level deep; a nested type is ' +
    'named, not expanded. Reads pass through on a dry run; writes (create/update/delete/add/remove/set/' +
    'place/apply/import/configure/…, and `manage*` with a writing `action`) are counted, capped and recorded.'
);
lines.push('');
lines.push(
  `${[...groups.values()].reduce((n, g) => n + g.length, 0)} functions in ${groups.size} modules.`
);
lines.push('');
for (const [group, entries] of [...groups.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`## ${group}`);
  lines.push('');
  for (const e of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const sigText = e.params.map(p => `${p.name}${p.optional ? '?' : ''}`).join(', ');
    lines.push(`### \`fvtt.${e.name}(${sigText})\``);
    lines.push('');
    if (e.doc) lines.push(e.doc, '');
    for (const p of e.params) {
      if (p.fields.length) {
        lines.push(`${p.name}${p.optional ? ' (optional)' : ''}:`);
        for (const f of p.fields) {
          lines.push(
            `- \`${f.name}${f.optional ? '?' : ''}: ${f.type}\`${f.doc ? ` — ${f.doc}` : ''}`
          );
        }
      } else {
        lines.push(`${p.name}${p.optional ? ' (optional)' : ''}: \`${p.type}\``);
      }
      lines.push('');
    }
    lines.push(`Returns \`${e.returns}\``);
    lines.push('');
  }
}
const text = `${lines.join('\n')}\n`;

if (check) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    // missing counts as stale
  }
  if (current !== text) {
    console.error(`docs/run-script-api.md is stale — run node scripts/measure/run-script-api.mjs`);
    process.exit(1);
  }
  console.log('docs/run-script-api.md is current');
} else {
  writeFileSync(OUT, text);
  console.log(
    `wrote ${relative(ROOT, OUT)}: ${text.length} chars, ${text.split('\n').length} lines`
  );
}
